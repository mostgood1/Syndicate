"""MLB daily sim off vendor, phase 3 (lane mlb-daily-sim-native-p3, 2026-10-16).

syndicate/features/mlb/native/tools/ holds whole, verbatim copies of every vendored tools/ file the MLB daily sim, the
refresh-worker's season-manifest launcher and the live lens reach, GENERATED by scripts/port_mlb_sim_engine.py. The gate
of record is the daily-sim parity on the fleet (deploys.md). This pins, in the suite: the tree is exactly what the
generator writes; importing the entry points loads no vendored module and puts nothing vendored on sys.path; every
script the daily sim launches is a NATIVE file; data roots stay on the vendored tree.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "vendor" / "mlb_bettingv2"
NATIVE = ROOT / "syndicate" / "features" / "mlb" / "native"


@pytest.mark.skipif(not VENDOR.exists(), reason="vendor tree absent")
def test_native_tree_matches_the_generator():
    r = subprocess.run([sys.executable, str(ROOT / "scripts" / "port_mlb_sim_engine.py"), "--check"],
                       capture_output=True, text=True, cwd=ROOT)
    assert r.returncode == 0 and "CHECK OK" in r.stdout, r.stdout + r.stderr[-3000:]


def test_entry_points_import_nothing_vendored():
    code = (
        "import sys, json\n"
        "before = set(sys.modules)\n"
        "import syndicate.features.mlb.native.tools.daily_update as DU\n"
        "import syndicate.features.mlb.native.tools.eval.build_season_betting_cards_manifest\n"
        "import syndicate.features.mlb.live_lens_port.app_slice\n"
        "vend = sorted(n for n, m in sys.modules.items() if n not in before\n"
        "    and '/vendor/' in (getattr(m, '__file__', '') or '').replace(chr(92), '/'))\n"
        "paths = [p for p in sys.path if 'vendor' in p.replace(chr(92), '/').split('/')]\n"
        "print(json.dumps({'vendored': vend, 'paths': paths, 'web': DU.write_daily_top_props_artifact.__module__}))\n"
    )
    r = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, cwd=ROOT)
    assert r.returncode == 0, r.stderr[-3000:]
    out = json.loads(r.stdout.strip().splitlines()[-1])
    assert out["vendored"] == [] and out["paths"] == [], out
    assert out["web"] == "syndicate.features.mlb.live_lens_port.app_slice"


def test_every_launched_script_is_a_native_file():
    """Each `_NATIVE_ROOT / "tools" / ...` script path in the copies names a file that exists in the native tree."""
    launched = 0
    for f in sorted((NATIVE / "tools").rglob("*.py")):
        text = f.read_text(encoding="utf-8")
        # The one exemption is a provenance LABEL (TOOLS_EDITS in the generator), marked on its line; nothing runs it.
        code = "\n".join(ln for ln in text.splitlines() if "# EDIT: the label production records" not in ln)
        assert not re.search(r"\b(?:_ROOT_DIR|_ROOT|REPO_ROOT)\s*/\s*\"tools\"", code), f"{f}: a vendored script path left"
        for m in re.finditer(r"_NATIVE_ROOT\s*/\s*\"tools\"((?:\s*/\s*\"[A-Za-z0-9_.]+\")+)", text):
            parts = re.findall(r"\"([A-Za-z0-9_.]+)\"", m.group(1))
            if parts[-1].endswith(".py"):
                assert NATIVE.joinpath("tools", *parts).is_file(), (f, parts)
                launched += 1
    assert launched >= 10, launched  # 11 at generation; a drop means the rule stopped firing


def test_data_root_is_engines_mlb():
    """The daily sim's DATA root (and subprocess cwd) is engines/mlb since lane mlb-engine-data-native-p4."""
    import syndicate.features.mlb.native.tools.daily_update as DU

    assert Path(DU._ROOT_DIR).resolve() == (ROOT / "engines" / "mlb").resolve()
    assert Path(DU._NATIVE_ROOT).resolve() == NATIVE.resolve()
