"""MLB engine off vendor, phase 2 of the live lens (lane mlb-sim-engine-native-p2, 2026-10-16).

syndicate/features/mlb/sim_engine/ (the whole vendored package) and syndicate/features/mlb/native/tools/ (phase 3: whole copies of the
tools helpers the live lens imports) are GENERATED by scripts/port_mlb_sim_engine.py. The gate of record is
scripts/mlb_live_lens_parity.py on the fleet (deploys.md). This pins, in the suite: the packages are exactly what the
generator writes, the live lens imports NO vendored module, and every relocated `Path(__file__)` still resolves to the
directory it did in vendor/.
"""
from __future__ import annotations

import importlib
import inspect
import json
import pkgutil
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
VENDOR_SIM = ROOT / "vendor" / "mlb_bettingv2" / "sim_engine"


@pytest.mark.skipif(not VENDOR_SIM.exists(), reason="vendor tree absent")
def test_generated_packages_match_the_generator():
    r = subprocess.run([sys.executable, str(ROOT / "scripts" / "port_mlb_sim_engine.py"), "--check"],
                       capture_output=True, text=True, cwd=ROOT)
    assert r.returncode == 0 and "CHECK OK" in r.stdout, r.stdout + r.stderr[-3000:]


def test_live_lens_imports_no_vendored_module():
    """In a FRESH interpreter -- this process may already hold vendored modules from other tests."""
    code = (
        "import sys, json\n"
        "before = set(sys.modules)\n"
        "import syndicate.features.mlb.live_lens_port.app_slice\n"
        "import syndicate.features.mlb.sim_engine, pkgutil, importlib\n"
        "import syndicate.features.mlb.sim_engine as S\n"
        "[importlib.import_module(m.name) for m in pkgutil.walk_packages(S.__path__, S.__name__ + '.')]\n"
        "print(json.dumps(sorted(n for n, m in sys.modules.items() if n not in before\n"
        "    and '/vendor/' in (getattr(m, '__file__', '') or '').replace(chr(92), '/'))))\n"
    )
    r = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, cwd=ROOT)
    assert r.returncode == 0, r.stderr[-3000:]
    assert json.loads(r.stdout.strip().splitlines()[-1]) == []


def test_vendored_file_targets_exist():
    import syndicate.features.mlb.sim_engine as S

    sites = {}
    for mi in pkgutil.walk_packages(S.__path__, S.__name__ + "."):
        vf = getattr(importlib.import_module(mi.name), "_VENDORED_FILE", None)
        if vf:
            sites[mi.name] = vf
    assert len(sites) >= 10, sites  # 13 at generation; a drop means the EDIT rule stopped firing
    if VENDOR_SIM.exists():
        assert all(Path(v).is_file() for v in sites.values()), sites


@pytest.mark.skipif(not VENDOR_SIM.exists(), reason="vendor tree absent")
def test_data_roots_resolve_as_in_vendor():
    """Every no-argument data-root helper that reads `__file__` returns the same directory in both trees."""
    sys.path.insert(0, str(VENDOR_SIM.parent))
    try:
        checked = 0
        for mod in ("forward_tuning", "pitcher_so_model"):
            n = importlib.import_module(f"syndicate.features.mlb.sim_engine.{mod}")
            v = importlib.import_module(f"sim_engine.{mod}")
            attr = "_ROOT" if mod == "forward_tuning" else "_DEFAULT_MODEL_PATH"
            assert str(getattr(n, attr)) == str(getattr(v, attr))
            checked += 1
        for mod in ("data.arsenal", "data.batted_ball", "data.conditional_mix", "data.quality", "data.statcast_bvp",
                    "data.roster_registry", "data.statcast_pitch_splits"):
            native = importlib.import_module(f"syndicate.features.mlb.sim_engine.{mod}")
            vendored = importlib.import_module(f"sim_engine.{mod}")
            for name, fn in inspect.getmembers(vendored, inspect.isfunction):
                if fn.__module__ != vendored.__name__ or inspect.signature(fn).parameters:
                    continue
                if "__file__" not in inspect.getsource(fn):
                    continue
                assert str(getattr(native, name)()) == str(fn()), f"{mod}.{name}"
                checked += 1
        assert checked >= 9, checked
    finally:
        sys.path.remove(str(VENDOR_SIM.parent))
