"""`#621` Phase 4 -- `_sim_many` itself emits the joint, on BOTH execution paths.

The unit tests around `JointAccumulator` prove the container works. They cannot
prove the producer is WIRED, and the standard is explicit that a passing unit
test over a fixture cannot detect an unfed production field. These tests call
the real `_sim_many` over real roster objects and read `out["joint"]`.

BOTH PATHS, DELIBERATELY. `_sim_many` branches on `workers > 1 and total_sims >
1`: above it the four-process `_simw_chunk` path, below it a serial loop. They
are separate copies of the accumulation and **`--workers` defaults to 4**, so a
test that only exercised `workers=1` would be testing the path production does
not take. The drift between those copies is `#334`/`#429`, and it has happened
three times in this file.
"""
